'use strict';

const fs = require('fs');
const path = require('path');
const mysql = require('mysql2/promise');
const dotenv = require('dotenv');

dotenv.config({ path: path.join(__dirname, '..', '.env') });

const OUTPUT = path.join(__dirname, '..', 'database', 'tecnoone_baseline.sql');
const GLOBAL_TABLES = ['modulos', 'permisos', 'planes', 'plan_modulos'];
const EXPECTED_COUNTS = { modulos: 20, permisos: 55, planes: 5, plan_modulos: 95 };

function portableCreate(sql) {
  return String(sql)
    .replace(/DEFINER=`[^`]+`@`[^`]+`\s*/gi, '')
    .replace(/AUTO_INCREMENT=\d+\s*/gi, '')
    .trim();
}

function quoteId(value) {
  return `\`${String(value).replace(/`/g, '``')}\``;
}

async function main() {
  const connection = await mysql.createConnection({
    host: process.env.DB_HOST,
    port: process.env.DB_PORT || 3306,
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    database: process.env.DB_NAME,
  });

  try {
    const [objects] = await connection.query(
      `SELECT TABLE_NAME, TABLE_TYPE FROM information_schema.TABLES
       WHERE TABLE_SCHEMA = DATABASE() ORDER BY TABLE_TYPE, TABLE_NAME`
    );
    const tables = objects.filter(row => row.TABLE_TYPE === 'BASE TABLE');
    const views = objects.filter(row => row.TABLE_TYPE === 'VIEW');
    if (tables.length !== 70) throw new Error(`tablas: esperado 70, obtenido ${tables.length}`);

    const [[roleScope]] = await connection.query(
      `SELECT COUNT(*) AS total,
              COUNT(DISTINCT empresa_id) AS empresas,
              SUM(empresa_id IS NULL) AS globales
         FROM roles`
    );
    if (Number(roleScope.total) !== 18 || Number(roleScope.empresas) !== 14 || Number(roleScope.globales) !== 0) {
      throw new Error('roles no coincide con la fuente validada (18 roles, 14 empresas, 0 globales)');
    }

    const [[criticalStructure]] = await connection.query(
      `SELECT
        (SELECT COUNT(*) FROM information_schema.TRIGGERS
          WHERE TRIGGER_SCHEMA = DATABASE()
            AND TRIGGER_NAME IN ('trg_auditoria_logs_append_only_update','trg_auditoria_logs_append_only_delete')) AS audit_triggers,
        (SELECT COUNT(*) FROM information_schema.KEY_COLUMN_USAGE
          WHERE TABLE_SCHEMA = DATABASE() AND REFERENCED_TABLE_NAME IS NOT NULL
            AND TABLE_NAME='deudores' AND COLUMN_NAME='sucursal_id') AS critical_fks`
    );
    if (Number(criticalStructure.audit_triggers) !== 2 || Number(criticalStructure.critical_fks) !== 1) {
      throw new Error('faltan triggers append-only o FK criticas en la fuente');
    }
    const lines = [
      '-- TecnoOne canonical baseline. Generated by scripts/generate-baseline.js.',
      '-- Contains complete structure and only approved global catalogs.',
      'SET NAMES utf8mb4;',
      'SET FOREIGN_KEY_CHECKS=0;',
      '',
    ];

    for (const object of [...tables, ...views]) {
      const [rows] = await connection.query(`SHOW CREATE ${object.TABLE_TYPE === 'VIEW' ? 'VIEW' : 'TABLE'} ${quoteId(object.TABLE_NAME)}`);
      const createSql = rows[0]['Create Table'] || rows[0]['Create View'];
      lines.push(`DROP ${object.TABLE_TYPE === 'VIEW' ? 'VIEW' : 'TABLE'} IF EXISTS ${quoteId(object.TABLE_NAME)};`);
      lines.push(`${portableCreate(createSql)};`, '');
    }

    for (const table of GLOBAL_TABLES) {
      const [[{ total }]] = await connection.query(`SELECT COUNT(*) AS total FROM ${quoteId(table)}`);
      if (Number(total) !== EXPECTED_COUNTS[table]) {
        throw new Error(`${table}: esperado ${EXPECTED_COUNTS[table]}, obtenido ${total}`);
      }
      const [rows, fields] = await connection.query(`SELECT * FROM ${quoteId(table)} ORDER BY 1`);
      const columns = fields.map(field => quoteId(field.name)).join(', ');
      for (const row of rows) {
        const values = fields.map(field => connection.escape(row[field.name])).join(', ');
        lines.push(`INSERT INTO ${quoteId(table)} (${columns}) VALUES (${values});`);
      }
      lines.push('');
    }

    const [triggers] = await connection.query(
      'SELECT TRIGGER_NAME FROM information_schema.TRIGGERS WHERE TRIGGER_SCHEMA = DATABASE() ORDER BY TRIGGER_NAME'
    );
    for (const trigger of triggers) {
      const [rows] = await connection.query(`SHOW CREATE TRIGGER ${quoteId(trigger.TRIGGER_NAME)}`);
      lines.push('DELIMITER $$', `${portableCreate(rows[0]['SQL Original Statement'])}$$`, 'DELIMITER ;', '');
    }

    for (const type of ['PROCEDURE', 'FUNCTION']) {
      const [routines] = await connection.query(
        'SELECT ROUTINE_NAME FROM information_schema.ROUTINES WHERE ROUTINE_SCHEMA = DATABASE() AND ROUTINE_TYPE = ? ORDER BY ROUTINE_NAME',
        [type]
      );
      for (const routine of routines) {
        const [rows] = await connection.query(`SHOW CREATE ${type} ${quoteId(routine.ROUTINE_NAME)}`);
        lines.push('DELIMITER $$', `${portableCreate(rows[0][`Create ${type === 'PROCEDURE' ? 'Procedure' : 'Function'}`])}$$`, 'DELIMITER ;', '');
      }
    }

    const [events] = await connection.query(
      'SELECT EVENT_NAME FROM information_schema.EVENTS WHERE EVENT_SCHEMA = DATABASE() ORDER BY EVENT_NAME'
    );
    for (const event of events) {
      const [rows] = await connection.query(`SHOW CREATE EVENT ${quoteId(event.EVENT_NAME)}`);
      lines.push('DELIMITER $$', `${portableCreate(rows[0]['Create Event'])}$$`, 'DELIMITER ;', '');
    }

    lines.push('SET FOREIGN_KEY_CHECKS=1;', '');
    fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
    fs.writeFileSync(OUTPUT, lines.join('\n'), { encoding: 'utf8', flag: 'w' });
    console.log(`Baseline generada: ${OUTPUT}`);
    console.log(`Tablas=${tables.length}, vistas=${views.length}, triggers=${triggers.length}`);
  } finally {
    await connection.end();
  }
}

main().catch(error => {
  console.error(`No se pudo generar la baseline: ${error.message}`);
  process.exit(1);
});
